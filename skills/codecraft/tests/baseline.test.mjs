import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'
import {
  BASELINE_FORMAT,
  applyBaseline,
  buildBaselineData,
  diffBaseline,
  fingerprint,
  loadBaseline,
  resolveBaselinePath,
  writeBaseline,
} from '../src/baseline.mjs'

const PACKAGE = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'))

void test('fingerprint: rule + file + message, no line number (edits do not invalidate)', () => {
  const a = { rule: 'A6', file: 'src/x.ts', line: 10, message: 'empty catch swallows failures (A6)' }
  const b = { rule: 'A6', file: 'src/x.ts', line: 99, message: 'empty catch swallows failures (A6)' }
  assert.equal(fingerprint(a), fingerprint(b))

  const c = { rule: 'A21', file: 'src/x.ts', line: 10, message: 'possible AWS access key; remove it and rotate the credential (A21)' }
  assert.notEqual(fingerprint(a), fingerprint(c))
})

void test('fingerprint: path separators normalize so one baseline works across Windows and POSIX', () => {
  const posix = { rule: 'A6', file: 'src/pages/home.ts', line: 1, message: 'm' }
  const windows = { rule: 'A6', file: 'src\\pages\\home.ts', line: 1, message: 'm' }
  assert.equal(fingerprint(posix), fingerprint(windows))
})

void test('resolveBaselinePath: true uses the default file, strings resolve against root', () => {
  assert.equal(path.basename(resolveBaselinePath('/r', true)), 'codecraft-baseline.json')
  assert.equal(resolveBaselinePath('/r', 'tmp/b.json'), path.resolve('/r', 'tmp/b.json'))
})

void test('loadBaseline: missing file is null, bad format throws, version drift warns', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'codecraft-baseline-'))
  try {
    assert.equal(loadBaseline(path.join(root, 'nope.json'), PACKAGE.version), null)

    const bad = path.join(root, 'bad.json')
    fs.writeFileSync(bad, JSON.stringify({ hello: 1 }))
    assert.throws(() => loadBaseline(bad, PACKAGE.version), /expected codecraft baseline format/)

    const file = path.join(root, 'b.json')
    writeBaseline(file, buildBaselineData(
      [{ rule: 'A6', file: 'src/x.ts', line: 1, message: 'm' }],
      PACKAGE.version,
      '2026-11-03',
    ))
    assert.equal(loadBaseline(file, PACKAGE.version).warnings.length, 0)

    const drifted = JSON.parse(fs.readFileSync(file, 'utf8'))
    drifted.toolVersion = '0.0.0'
    fs.writeFileSync(file, JSON.stringify(drifted))
    const loaded = loadBaseline(file, PACKAGE.version)
    assert.equal(loaded.warnings.length, 1)
    assert.match(loaded.warnings[0], /was generated by codecraft 0\.0\.0/)
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})

void test('applyBaseline: splits known (suppressed) from new (active) findings', () => {
  const known = { rule: 'A6', file: 'src/a.ts', line: 3, message: 'empty catch swallows failures; return a Result or handle the error (A6)' }
  const moved = { ...known, line: 42 }
  const fresh = { rule: 'A6', file: 'src/b.ts', line: 7, message: 'promise catch handler silently discards the failure; return a Result or handle the error (A6)' }
  const data = buildBaselineData([known], PACKAGE.version, '2026-11-03')

  assert.equal(data.format, BASELINE_FORMAT)
  assert.equal(data.count, 1)

  const { active, suppressed } = applyBaseline([moved, fresh], { data })
  assert.deepEqual(active, [fresh])
  assert.deepEqual(suppressed, [moved])

  const none = applyBaseline([known], null)
  assert.equal(none.active.length, 1)
  assert.equal(none.suppressed.length, 0)
})

void test('baseline: critical (secret) findings are never baselined nor suppressed', () => {
  const secret = {
    rule: 'A21',
    file: '.env',
    line: 1,
    message: 'plaintext API_KEY; move it to env / config center and rotate (A21)',
    critical: true,
  }

  // 生成基线时排除密钥。
  const data = buildBaselineData([secret], PACKAGE.version, '2026-11-03')
  assert.equal(data.count, 0)
  assert.deepEqual(Object.keys(data.findings), [])

  // 即便旧基线文件里已存在该指纹，也不抑制（防御历史文件）。
  const forced = {
    data: {
      ...data,
      count: 1,
      findings: { [fingerprint(secret)]: { rule: 'A21', file: '.env', message: secret.message, since: '2026-11-01' } },
    },
  }
  const applied = applyBaseline([secret], forced)
  assert.equal(applied.active.length, 1)
  assert.equal(applied.suppressed.length, 0)
})

void test('diffBaseline: added / removed drive the shrink-only ratchet', () => {
  const a = { rule: 'A6', file: 'src/a.ts', line: 1, message: 'm-a' }
  const b = { rule: 'A6', file: 'src/b.ts', line: 1, message: 'm-b' }
  const prev = buildBaselineData([a, b], PACKAGE.version, '2026-11-01')
  const shrunk = buildBaselineData([a], PACKAGE.version, '2026-11-03')
  const grown = buildBaselineData([a, b, { rule: 'A2', file: 'src/c.ts', line: 1, message: 'm-c' }], PACKAGE.version, '2026-11-03')

  assert.deepEqual(diffBaseline(prev, shrunk), { added: [], removed: [fingerprint(b)] })
  assert.deepEqual(diffBaseline(prev, grown).added, [fingerprint({ rule: 'A2', file: 'src/c.ts', line: 1, message: 'm-c' })])
})

void test('buildBaselineData: keys are sorted for stable, merge-friendly files', () => {
  const findings = [
    { rule: 'A6', file: 'src/z.ts', line: 1, message: 'm' },
    { rule: 'A2', file: 'src/a.ts', line: 1, message: 'm' },
  ]
  const data = buildBaselineData(findings, PACKAGE.version, '2026-11-03')
  assert.deepEqual(Object.keys(data.findings), Object.keys(data.findings).sort())
})
