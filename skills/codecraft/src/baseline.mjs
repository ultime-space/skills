import fs from 'node:fs'
import path from 'node:path'

/** 基线文件格式版本；字段或指纹算法变化时递增，旧版本文件直接拒绝并要求重建（被动失效显式化）。 */
export const BASELINE_FORMAT = 1
export const DEFAULT_BASELINE_FILE = 'codecraft-baseline.json'

/**
 * 指纹 = 规则 + 文件 + 稳定消息，不含行号（抗编辑，R3）。
 * 路径统一用 `/`，避免 Windows 与 POSIX 对同一份基线全部失配。
 * A21 的 message 只含密钥类型与字段名、不含密钥值，指纹入库不泄露敏感内容。
 */
export function fingerprint(finding) {
  const file = String(finding.file ?? '').replace(/\\/g, '/')
  return `${finding.rule}|${file}|${finding.message}`
}

/** baseline 取值：true（默认路径）或非空相对路径；均相对 --root 解析。 */
export function resolveBaselinePath(root, value) {
  const file = value === true ? DEFAULT_BASELINE_FILE : value
  return path.resolve(root, file)
}

/** 读基线；文件不存在返回 null。格式不符直接抛错（exit 2），不让静默失效伪装成「全绿」。 */
export function loadBaseline(file, toolVersion) {
  if (!fs.existsSync(file)) return null

  let data
  try {
    data = JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch (error) {
    throw new Error(`invalid baseline ${file}: ${error.message} (fix the JSON or rebuild with --update-baseline --force)`)
  }
  if (
    !data ||
    data.tool !== 'codecraft' ||
    data.format !== BASELINE_FORMAT ||
    typeof data.findings !== 'object' ||
    data.findings == null ||
    Array.isArray(data.findings)
  ) {
    throw new Error(
      `invalid baseline ${file}: expected codecraft baseline format ${BASELINE_FORMAT} (rebuild with --update-baseline --force)`,
    )
  }

  const warnings = []
  if (data.toolVersion !== toolVersion) {
    // 被动失效提示：工具版本变了，条目可能漂移；不阻断，由使用者决定是否重建（主动收缩）。
    warnings.push(
      `baseline ${file} was generated by codecraft ${data.toolVersion ?? '(unknown)'}, running ${toolVersion}; fingerprints may drift — rebuild with --update-baseline if findings shift unexpectedly`,
    )
  }
  return { file, data, warnings }
}

/** 密钥（critical）永不进基线：A21 不可豁免，只能移除并轮换，不能靠快照压掉。 */
export function isBaselineable(finding) {
  return finding?.critical !== true
}

/** 命中基线的 findings 被抑制（存量），未命中的是新增——退出码只看新增。 */
export function applyBaseline(findings, baseline) {
  if (!baseline) return { active: findings, suppressed: [] }
  const known = baseline.data.findings
  const active = []
  const suppressed = []
  for (const finding of findings) {
    const knownFingerprint =
      isBaselineable(finding) && Object.prototype.hasOwnProperty.call(known, fingerprint(finding))
    if (knownFingerprint) suppressed.push(finding)
    else active.push(finding)
  }
  return { active, suppressed }
}

/** 从 findings 构建基线数据；critical（密钥）被排除。键排序保证文件内容稳定、diff 友好。 */
export function buildBaselineData(findings, toolVersion, updatedAt) {
  const entries = {}
  for (const finding of findings) {
    if (!isBaselineable(finding)) continue
    entries[fingerprint(finding)] = {
      rule: finding.rule,
      file: finding.file,
      message: finding.message,
      since: updatedAt,
    }
  }
  const sorted = {}
  for (const key of Object.keys(entries).sort()) sorted[key] = entries[key]
  return {
    format: BASELINE_FORMAT,
    tool: 'codecraft',
    toolVersion,
    updatedAt,
    count: Object.keys(sorted).length,
    findings: sorted,
  }
}

/** 新旧基线差集：added 用于「只减不增」棘轮，removed 是主动收缩的进度。 */
export function diffBaseline(previous, next) {
  const prevKeys = new Set(Object.keys(previous?.findings ?? {}))
  const nextKeys = new Set(Object.keys(next?.findings ?? {}))
  return {
    added: [...nextKeys].filter((key) => !prevKeys.has(key)),
    removed: [...prevKeys].filter((key) => !nextKeys.has(key)),
  }
}

/**
 * 两组 findings 的差集（--compare 的内核）：指纹同基线（规则 + 文件 + 消息，不含行号）。
 * added = 本次有、上次没有；resolved = 上次有、本次没有。
 */
export function diffFindings(previousFindings, currentFindings) {
  const prevByFingerprint = new Map()
  for (const finding of previousFindings ?? []) prevByFingerprint.set(fingerprint(finding), finding)
  const currentFingerprints = new Set((currentFindings ?? []).map(fingerprint))
  return {
    added: (currentFindings ?? []).filter((finding) => !prevByFingerprint.has(fingerprint(finding))),
    resolved: [...prevByFingerprint.entries()].filter(([key]) => !currentFingerprints.has(key)).map(([, finding]) => finding),
  }
}

export function writeBaseline(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`)
}
